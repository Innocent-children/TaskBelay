func TestGoTestCasesSubtestsAndLiteralTableRows(t *testing.T) {
	source := `package p
import "testing"
func TestPlain(t *testing.T){ if work()!=1 { t.Fatal("result") } }
func TestNested(t *testing.T){t.Run("outer",func(t *testing.T){ t.Run("inner",func(t *testing.T){ t.Error("inner") }) })}
func TestTable(t *testing.T){cases:=[]struct{name string; value int}{{name:"one",value:1},{name:"two",value:2}}; for _,tc:=range cases { t.Run(tc.name,func(t *testing.T){ if work()!=tc.value {t.Fatal("table")} }) }}
func TestPositional(t *testing.T){cases:=[]struct{name string; value int}{{"three",3},{"four",4}}; for _,tc:=range cases { t.Run(tc.name,func(t *testing.T){ if work()!=tc.value {t.Fatal("table")} }) }}
func TestLoop(t *testing.T){ for _,value:=range []int{1,2} {if work()!=value {t.Fatal("loop")}} }
func TestMain(m *testing.M){}
func Testwrong(t *testing.T){}
func BenchmarkRun(b *testing.B){}
func FuzzRun(f *testing.F){}
func ExampleRun(){}
`
	file := scanSources(t, map[string]string{"run_test.go": source}).Files["run_test.go"]
	var names []string
	for _, test := range file.Tests {
		names = append(names, test.Name)
		if len(test.Assertions) != 1 || test.Assertions[0].Kind != "result" {
			t.Fatal("assertion missing", test)
		}
		if test.Name == "TestTable/one" && len(test.Parameters) != 1 {
			t.Fatal("parameter row missing", test)
		}
	}
	want := []string{"TestPlain", "TestNested/outer/inner", "TestTable/one", "TestTable/two", "TestPositional/three", "TestPositional/four", "TestLoop"}
	if !slices.Equal(names, want) || !file.Operations["tests"].Complete {
		t.Fatal(names, file.Operations["tests"], file.Missing)
	}
}

func TestGoUnknownOrDuplicateSubtestNamesKeepOuterWhole(t *testing.T) {
	source := `package p
import "testing"
func TestDynamic(t *testing.T){ t.Run(name(),func(t *testing.T){t.Fatal("x")}) }
func TestDuplicate(t *testing.T){ t.Run("same",func(t *testing.T){}); t.Run("same",func(t *testing.T){}) }
func TestOther(t *testing.T){ x:=other{}; x.Run("not a subtest",func(t *testing.T){}) }
func TestRepeatedLoop(t *testing.T){for _,v:=range []int{1,2}{ t.Run("same",func(t *testing.T){t.Log(v)}) }}
type other struct{}
`
	file := scanSources(t, map[string]string{"run_test.go": source}).Files["run_test.go"]
	if len(file.Tests) != 4 || file.Tests[0].Name != "TestDynamic" || len(file.Tests[0].Unknown) == 0 || file.Tests[1].Name != "TestDuplicate" || len(file.Tests[1].Unknown) == 0 || file.Tests[2].Name != "TestOther" || file.Tests[3].Name != "TestRepeatedLoop" || len(file.Tests[3].Unknown) == 0 {
		t.Fatal(file.Tests)
	}
	if file.Operations["tests"].Complete {
		t.Fatal("unknown names treated as enumeration complete")
	}
}

func TestGoSubtestKeepsSharedSetupAssertions(t *testing.T) {
	file := scanSources(t, map[string]string{"shared_test.go": `package p
import("testing";"github.com/stretchr/testify/mock")
func TestShared(t *testing.T){if prepare()!=1 {t.Fatal("setup")};t.Run("a",func(t *testing.T){var m mock.Mock;m.AssertCalled(t,"save")})}
`}).Files["shared_test.go"]
	if len(file.Tests) != 1 || len(file.Tests[0].Assertions) != 2 || file.Tests[0].Assertions[0].Kind != "result" || file.Tests[0].Assertions[1].Kind != "mock" || !slices.Contains(file.Tests[0].References, "prepare") {
		t.Fatal(file.Tests, file.Missing)
	}
}

func TestGoEXPECTRequiresGomockReceiverAndGeneratedMetadata(t *testing.T) {
	snapshot := scanSources(t, map[string]string{
		"mock_generated.go": `// Code generated by MockGen. DO NOT EDIT.
package p
import "go.uber.org/mock/gomock"
type MockSave struct {ctrl *gomock.Controller; recorder *MockSaveRecorder}
type MockSaveRecorder struct {mock *MockSave}
func NewMockSave(ctrl *gomock.Controller) *MockSave{return nil}
func (m *MockSave) EXPECT() *MockSaveRecorder{return m.recorder}
`,
		"save_test.go": `package p
import ("testing";"go.uber.org/mock/gomock")
func TestSave(t *testing.T){ctrl:=gomock.NewController(t); m:=NewMockSave(ctrl); m.EXPECT().Save().Times(1)}
func TestFake(t *testing.T){fake:=Fake{};fake.EXPECT()}
type Fake struct{}
func (Fake) EXPECT(){}
func TestShadow(t *testing.T){NewMockSave:=func(*gomock.Controller) Fake{return Fake{}};m:=NewMockSave(nil);m.EXPECT()}
`,
	})
	file := snapshot.Files["save_test.go"]
	if len(file.Tests) != 3 || len(file.Tests[0].Assertions) != 1 || file.Tests[0].Assertions[0].Kind != "mock" || len(file.Tests[0].Unknown) != 0 || len(file.Tests[1].Assertions) != 0 || len(file.Tests[2].Assertions) != 0 {
		t.Fatal(file.Tests, file.Missing)
	}
	if generated := snapshot.Files["mock_generated.go"]; len(generated.Declarations) != 0 || len(generated.Tests) != 0 || !generated.Kind.Generated {
		t.Fatal("generated source included in simplification", generated)
	}
}

func TestGoAssertionsUseResolvedImportsAndReceivers(t *testing.T) {
	source := `package p
import("testing"; "github.com/stretchr/testify/assert"; "github.com/stretchr/testify/mock"; "go.uber.org/mock/gomock")
func TestAssertions(t *testing.T){ ctrl:=gomock.NewController(t); ctrl.Finish(); var m mock.Mock; m.AssertCalled(t,"save"); assert.Equal(t,1,work()); a:=assert.New(t);a.Equal(1,work()) }
func TestShadow(t *testing.T){ assert:=other{}; assert.Equal(1,2) }
type other struct{}
`
	file := scanSources(t, map[string]string{"assert_test.go": source}).Files["assert_test.go"]
	if len(file.Tests) != 2 {
		t.Fatal(file.Tests, file.Missing)
	}
	var kinds []string
	for _, assertion := range file.Tests[0].Assertions {
		kinds = append(kinds, assertion.Kind)
	}
	if !slices.Equal(kinds, []string{"mock", "mock", "result", "result"}) || len(file.Tests[1].Assertions) != 0 {
		t.Fatal(file.Tests)
	}
}
