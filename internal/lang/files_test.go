package lang

import "testing"

func TestDocumentedSourceExtensions(t *testing.T) {
	for _, file := range []string{"a.go", "a.py", "a.js", "a.jsx", "a.mjs", "a.cjs", "a.ts", "a.tsx", "a.mts", "a.cts", "a.java", "a.rs", "a.c", "a.cpp", "a.cs", "a.rb", "a.php"} {
		if got := Classify(file, nil); !got.Source || got.Language == "" {
			t.Errorf("%s: %+v", file, got)
		}
	}
}

func TestClassificationKeepsCapabilitiesSeparate(t *testing.T) {
	for _, test := range []struct {
		name, source string
		check        func(FileKind) bool
	}{
		{"pkg/service.go", "// Code GENERATED by tool; DO NOT EDIT.\npackage pkg", func(k FileKind) bool { return k.Source && k.Generated }},
		{"src/a.ts", "\n\n\n\n// @generated\n", func(k FileKind) bool { return k.Generated }},
		{"src/b.ts", "\n\n\n\n\n// @generated\n", func(k FileKind) bool { return !k.Generated }},
		{"src/a.d.ts", "", func(k FileKind) bool { return k.Stub && !k.Source }},
		{"src/a.pyi", "", func(k FileKind) bool { return k.Stub && !k.Source }},
		{"vendor/lib/a.go", "", func(k FileKind) bool { return k.Dependency }},
		{"node_modules/lib/a.js", "", func(k FileKind) bool { return k.Dependency }},
		{"src/range_test.go", "", func(k FileKind) bool { return k.Source && k.Test }},
		{"test/test_api.py", "", func(k FileKind) bool { return k.Source && k.Test }},
		{"src/test/java/RangeTest.java", "", func(k FileKind) bool { return k.Source && k.Test }},
		{"src/lib.rs", "#[cfg(test)] mod tests {}", func(k FileKind) bool { return k.Source && !k.Test }},
		{"tests/input.json", "{}", func(k FileKind) bool { return k.TestData && !k.Source }},
		{"testdata/input.go", "package sample", func(k FileKind) bool { return k.TestData }},
		{"docs/readme.md", "", func(k FileKind) bool { return !k.Source && !k.Test }},
		{"docs/readme.rst", "Title\n=====\n", func(k FileKind) bool { return !k.Source && !k.Test }},
		{"tests/example.rst", "Title\n=====\n", func(k FileKind) bool { return k.TestData && !k.Source && !k.Test }},
		{"sub/Cargo.lock", "", func(k FileKind) bool { return k.Lock && !k.Source }},
	} {
		t.Run(test.name, func(t *testing.T) {
			if got := Classify(test.name, []byte(test.source)); !test.check(got) {
				t.Fatal(got)
			}
		})
	}
}
